modeButtons.forEach(btn => {
    btn.addEventListener('click', () => {
        modeButtons.forEach(b => b.classList.remove('active'));
        btn.classList.add('active');
        selectedMode = btn.getAttribute('data-mode');
    });
});

// 3. إضافة حقول مدخلات لاعبين جدد بشكل ديناميكي لا نهائي
addPlayerBtn.addEventListener('click', () => {
    const playerGroups = document.querySelectorAll('.player-input-group');
    const newPlayerNumber = playerGroups.length + 1;
    
    const newInputGroup = document.createElement('div');
    newInputGroup.classList.add('player-input-group');
    newInputGroup.innerHTML = `<input type="text" class="player-input" placeholder="اسم اللاعب ${newPlayerNumber}...">`;
    playersList.appendChild(newInputGroup);
    
    // النزول التلقائي بالسكرول لأسفل القائمة
    playersList.scrollTop = playersList.scrollHeight;
});

// 4. دالة التحقق وبدء اللعب وفلترة الكروت
startGameBtn.addEventListener('click', () => {
    players = [];
    const inputs = document.querySelectorAll('.player-input');
    
    inputs.forEach(input => {
        const name = input.value.trim();
        if (name !== "") players.push(name);
    });

    // ملء تلقائي في حال عدم كتابة أسماء كافية لضمان عمل الجيم
    if (players.length < 2) {
        players = ["لاعب 1", "لاعب 2"];
    }

    // فلترة الأسئلة حسب اختيار الفئة
    if (selectedMode === 'all') {
        filteredQuestions = [...questions];
    } else {
        filteredQuestions = questions.filter(q => q.category === selectedMode);
    }

    // خلط ترتيب مصفوفة الـ 150 موقفاً عشوائياً لإضافة إثارة (Shuffle Array)
    filteredQuestions.sort(() => Math.random() - 0.5);

    // تصفير مؤشرات اللعب
    currentQuestionIndex = 0;
    currentPlayerIndex = 0;

    // نقل شاشات العرض
    setupScreen.classList.remove('active');
    gameScreen.classList.add('active');

    // سحب الموقف الأول فوراً للاعب الأول
    showNextQuestion();
});

// 5. زر العودة من اللعب إلى شاشة الإعداد والترحيب
backBtn.addEventListener('click', () => {
    gameScreen.classList.remove('active');
    setupScreen.classList.add('active');
    questionText.innerText = "اضغط على الزر بالأسفل لسحب الموقف الأول!";
    cardCategory.innerText = "لو.. 🤔";
});

// 6. دالة سحب وعرض الكروت وتدوير الأدوار تلقائياً بين اللاعبين
function showNextQuestion() {
    if (filteredQuestions.length === 0) return;

    // إعادة تدوير الأسئلة عشوائياً مجدداً إذا انتهت كل الكروت
    if (currentQuestionIndex >= filteredQuestions.length) {
        filteredQuestions.sort(() => Math.random() - 0.5);
        currentQuestionIndex = 0;
    }

    // تحديث اسم اللاعب الذي عليه الدور في شاشة اللعب
    const player = players[currentPlayerIndex];
    currentPlayerName.innerText = player;

    // جلب نص الموقف وعرضه داخل الكارت
    const currentQuestion = filteredQuestions[currentQuestionIndex];
    questionText.innerText = currentQuestion.text;

    // تغيير التاج (Tag) العلوي للكارت بناءً على فئة الموقف السري
    let categoryName = "عام 💥";
    if (currentQuestion.category === 'tech') categoryName = "تكنولوجيا 📱";
    if (currentQuestion.category === 'social') categoryName = "اجتماعي 🤐";
    if (currentQuestion.category === 'scandal') categoryName = "فضائح 🤦‍♂️";
    cardCategory.innerText = categoryName;

    // تشغيل أنيميشن الكارت الحركي (Bounce Effect) عند سحب سؤال جديد
    questionCard.classList.remove('card-bounce');
    void questionCard.offsetWidth; // حيلة برمجية لعمل Reset وإعادة تشغيل الأنيميشن
    questionCard.classList.add('card-bounce');

    // تجهيز العدادات للدور القادم واللاعب التالي
    currentQuestionIndex++;
    currentPlayerIndex = (currentPlayerIndex + 1) % players.length;
}

// 7. ربط أزرار التحكم والانسحاب داخل الجيم
nextBtn.addEventListener('click', showNextQuestion);

